import argparse
import os
import random

from fly_brain_rc.config import SIM, DRIVE
from fly_brain_rc.sim.car_model import build_model_xml


def _draw_once(rng):
    cfg = SIM
    o = cfg.arena_half
    start = (0.0, 0.0)
    obstacles = []
    for _ in range(cfg.n_obstacles):
        for attempt in range(200):
            x = rng.uniform(-o + 1.0, o - 1.0)
            y = rng.uniform(-o + 1.0, o - 1.0)
            if math_hypot(x - start[0], y - start[1]) < 1.2:
                continue
            if all(math_hypot(x - ox, y - oy) > 1.0 for (ox, oy), _ in obstacles):
                break
        obstacles.append(
            (
                (x, y),
                (
                    rng.uniform(0.20, 0.45),
                    rng.uniform(0.45, 0.75),
                    rng.uniform(0.65, 0.95),
                ),
            )
        )
    gx, gy = None, None
    for attempt in range(200):
        gx = rng.uniform(-o + 1.2, o - 1.2)
        gy = rng.uniform(-o + 1.2, o - 1.2)
        if math_hypot(gx, gy) > 1.6 and all(
            math_hypot(gx - ox, gy - oy) > 1.0 for (ox, oy), _ in obstacles
        ):
            break
    return obstacles, (float(gx), float(gy))


def build_scene(seed: int, episode: int = 0) -> str:
    rng = random.Random(seed)
    obstacles, goal = (None, None)
    for _ in range(episode + 1):
        obstacles, goal = _draw_once(rng)
    gx, gy = goal
    xml = build_model_xml(SIM, DRIVE, obstacles, goal, steer_actuator=True)
    header = (
        f'<!-- seed={seed} episode={episode} n_obstacles={SIM.n_obstacles} '
        f'goal=({gx:.3f}, {gy:.3f}) generated by scripts/export_scene.py -->\n'
    )
    return header + xml


def math_hypot(a, b):
    return (a * a + b * b) ** 0.5


def main():
    ap = argparse.ArgumentParser(description="Export a standalone MJCF scene for MuJoCo simulate")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", default=None, help="e.g. scenes/scene.xml")
    args = ap.parse_args()

    out = args.out or os.path.join("scenes", f"scene_seed{args.seed}.xml")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    xml = build_scene(args.seed)
    with open(out, "w") as f:
        f.write(xml)
    print(f"wrote {out} (seed={args.seed})")
    print("run with:  /Applications/MuJoCo.app/Contents/MacOS/simulate " + out)


if __name__ == "__main__":
    main()
